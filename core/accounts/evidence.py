"""Payout evidence pack (Update Blueprint v2.1, U5).

Deterministic, no LLM. Builds a ZIP with every trade's decision trail,
compliance snapshots, network history, the audit slice with hash-chain
verification, firm support confirmations and strategy fingerprints.

Determinism: fixed ZipInfo timestamps, sorted file names, sorted rows —
two builds over the same inputs produce byte-identical archives.
"""
from __future__ import annotations

import csv
import io
import json
import zipfile
from pathlib import Path

ZIP_EPOCH = (2020, 1, 1, 0, 0, 0)     # fixed timestamp for determinism

TRADE_COLUMNS = ["account_id", "symbol", "side", "lot", "entry_price",
                 "exit_price", "pnl", "strategy_version_id",
                 "signal_time_ms", "order_time_ms", "fill_time_ms",
                 "hold_duration_s", "modification_count",
                 "intended_risk_pct", "risk_decision_trail",
                 "compliance_reasons", "ruleset_version", "ruleset_hash",
                 "session_profile"]

SNAPSHOT_COLUMNS = ["account_id", "day_utc", "payload_json"]


class DailySnapshotStore:
    """Per-day compliance state snapshots (JSONL, append-only)."""

    def __init__(self, path: str | Path = "state/compliance_snapshots.jsonl"):
        self.path = Path(path)

    def record(self, account_id: str, day_utc: str, payload: dict,
               ts_ms: int | None = None) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.path.open("a") as f:
            f.write(json.dumps({"account_id": account_id,
                                "day_utc": day_utc, "payload": payload,
                                "ts_ms": ts_ms}) + "\n")

    def entries(self, account_id: str, from_ms: int,
                to_ms: int) -> list[dict]:
        if not self.path.exists():
            return []
        out = []
        for line in self.path.read_text().splitlines():
            if not line.strip():
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            if (rec.get("account_id") == account_id
                    and from_ms <= rec.get("ts_ms", 0) <= to_ms):
                out.append(rec)
        return sorted(out, key=lambda r: (r.get("ts_ms", 0),
                                          r.get("day_utc", "")))


def scan_for_secrets(texts: list[str], secret_values: list[str]) -> list[str]:
    """Return which secret values leaked into the given texts (used by
    tests and by the pack builder as a final gate)."""
    leaked = []
    for secret in secret_values:
        if secret and any(secret in t for t in texts):
            leaked.append(secret)
    return leaked


def _csv_bytes(columns: list[str], rows: list[dict]) -> bytes:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=columns, extrasaction="ignore")
    writer.writeheader()
    for row in sorted(rows, key=lambda r: json.dumps(r, sort_keys=True)):
        writer.writerow({c: row.get(c, "") for c in columns})
    return buf.getvalue().encode()


def build_evidence_pack(account_id: str, from_ms: int, to_ms: int, *,
                        trades: list[dict],
                        compliance_snapshots: list[dict],
                        network_history: list[dict],
                        audit_entries: list[dict],
                        chain_verification: str,
                        firm_support_confirmations: list[dict] | None = None,
                        strategy_rationales: dict | None = None,
                        strategy_fingerprints: list[dict] | None = None,
                        ) -> bytes:
    """Assemble the ZIP. Every input is plain data; nothing is fetched,
    nothing is generated by an LLM."""
    firm_support_confirmations = firm_support_confirmations or []
    strategy_rationales = strategy_rationales or {}
    strategy_fingerprints = strategy_fingerprints or []

    files: dict[str, bytes] = {
        "trades.csv": _csv_bytes(TRADE_COLUMNS, [
            {**t, "risk_decision_trail": json.dumps(
                t.get("risk_decision_trail", []), sort_keys=True),
             "compliance_reasons": json.dumps(
                 t.get("compliance_reasons", []), sort_keys=True)}
            for t in trades
            if from_ms <= t.get("fill_time_ms", 0) <= to_ms]),
        "compliance_snapshots.csv": _csv_bytes(SNAPSHOT_COLUMNS, [
            {**s, "payload_json": json.dumps(s.get("payload", {}),
                                             sort_keys=True)}
            for s in compliance_snapshots]),
        "network_history.json": json.dumps(network_history, indent=1,
                                           sort_keys=True).encode(),
        "audit_slice.jsonl": "\n".join(
            json.dumps(e, sort_keys=True, default=str)
            for e in audit_entries
            if from_ms <= e.get("ts_ms", 0) <= to_ms).encode(),
        "chain_verification.txt": chain_verification.encode(),
        "firm_support_confirmations.json": json.dumps(
            firm_support_confirmations, indent=1, sort_keys=True).encode(),
        "strategy_rationales.json": json.dumps(
            strategy_rationales, indent=1, sort_keys=True).encode(),
        "strategy_fingerprints.json": json.dumps(
            strategy_fingerprints, indent=1, sort_keys=True).encode(),
    }
    files["manifest.json"] = json.dumps({
        "account_id": account_id, "from_ms": from_ms, "to_ms": to_ms,
        "files": sorted(files),
        "chain_verification": chain_verification,
    }, indent=1, sort_keys=True).encode()

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for name in sorted(files):
            info = zipfile.ZipInfo(name, date_time=ZIP_EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(info, files[name])
    return buf.getvalue()
